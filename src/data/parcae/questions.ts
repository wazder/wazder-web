import type { Person, Question, Section } from '../../lib/parcae/types';

const C = (id: string, q: string, opts: string[], hint?: string): Question => ({
  id,
  q,
  t: 'choice',
  opts,
  hint,
});
const M = (id: string, q: string, opts: string[], hint?: string): Question => ({
  id,
  q,
  t: 'multi',
  opts,
  hint: hint ?? 'Birden fazla seçebilirsin.',
});
const S = (id: string, q: string, lo: string, hi: string): Question => ({ id, q, t: 'scale', lo, hi });
const T = (id: string, q: string, ph?: string, hint?: string): Question => ({
  id,
  q,
  t: 'text',
  ph,
  hint,
  note: false,
});
const X = (id: string, q: string, ph?: string, hint?: string): Question => ({
  id,
  q,
  t: 'short',
  ph,
  hint,
  note: false,
});
const OWN = (id: string, q: string): Question => ({
  id,
  q,
  t: 'choice',
  opts: ['Hasan', 'Nihat', 'Bilge', 'Ortak'],
  note: false,
});

